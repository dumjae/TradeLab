function slugify(code: string, title: string): string {
  const cleanCode = code.toLowerCase().replace(/\./g, '-');
  const cleanTitle = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `idx-${cleanCode}-${cleanTitle}`;
}

function buildIndexLesson(t: IndexTopicTuple): DecoupledLessonNode {
  const [
    code,
    title,
    level,
    estimatedMinutes,
    diagramKind,
    prerequisiteCodes,
    overviewEn,
    overviewTaglish,
    objectives,
    keyPoints,
    practicalExample,
    quiz,
    linkedDeepLessonSlug,
    limitationsNote,
  ] = t;

  return {
    id: `idx-${code.toLowerCase().replace(/\./g, '-')}`,
    code,
    slug: slugify(code, title),
    title,
    overviewEn,
    overviewTaglish,
    objectives: [...objectives],
    keyPoints: [...keyPoints],
    ...(limitationsNote ? { limitationsNote } : {}),
    practicalExample,
    level,
    pillar: 'specializations',
    supportedMarkets: ['indices'],
    prerequisiteCodes,
    estimatedMinutes,
    ...(linkedDeepLessonSlug ? { linkedDeepLessonSlug } : {}),
    diagramKind,
    quiz,
  };
}

