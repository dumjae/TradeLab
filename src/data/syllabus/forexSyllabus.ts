function slugify(code: string, title: string): string {
  const cleanCode = code.toLowerCase().replace(/\./g, '-');
  const cleanTitle = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `fx-${cleanCode}-${cleanTitle}`;
}

function buildForexLesson(t: ForexTopicTuple): DecoupledLessonNode {
  const [
    code,
    title,
    level,
    estimatedMinutes,
    diagramKind,
    prerequisiteCodes,
    overviewEn,
    overviewTaglish,
    objectives,
    keyPoints,
    practicalExample,
    quiz,
    linkedDeepLessonSlug,
    limitationsNote,
  ] = t;

  return {
    id: `fx-${code.toLowerCase().replace(/\./g, '-')}`,
    code,
    slug: slugify(code, title),
    title,
    overviewEn,
    overviewTaglish,
    objectives: [...objectives],
    keyPoints: [...keyPoints],
    ...(limitationsNote ? { limitationsNote } : {}),
    practicalExample,
    level,
    pillar: 'specializations',
    supportedMarkets: ['forex'],
    prerequisiteCodes,
    estimatedMinutes,
    ...(linkedDeepLessonSlug ? { linkedDeepLessonSlug } : {}),
    diagramKind,
    quiz,
  };
}

