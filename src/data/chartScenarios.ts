/** NY-tagged times in scenario text become PH time; candle data is never touched. */
export const CHART_SCENARIOS: ChartScenario[] = deepLocalizeMarketTimes(RAW_CHART_SCENARIOS, {
  skipKeys: ['candles'],
});

export const CHART_SCENARIOS_BY_ID: Record<string, ChartScenario> =
  Object.fromEntries(CHART_SCENARIOS.map((scenario) => [scenario.id, scenario]));

export function getChartScenarioById(id: string): ChartScenario | undefined {
  return CHART_SCENARIOS_BY_ID[id];
}

export function getChartScenariosByLessonSlug(
  lessonSlug: string,
): ChartScenario[] {
  return CHART_SCENARIOS.filter((scenario) => scenario.lessonSlug === lessonSlug);
}

export function getChartScenariosForLesson(lesson: {
  slug: string;
  chartScenarioIds: string[];
}): ChartScenario[] {
  const seen = new Set<string>();
  const matched: ChartScenario[] = [];

  for (const scenario of CHART_SCENARIOS) {
    if (scenario.lessonSlug === lesson.slug && !seen.has(scenario.id)) {
      seen.add(scenario.id);
      matched.push(scenario);
    }
  }

  for (const id of lesson.chartScenarioIds) {
    const scenario = CHART_SCENARIOS_BY_ID[id];
    if (scenario && !seen.has(scenario.id)) {
      seen.add(scenario.id);
      matched.push(scenario);
    }
  }

  return matched;
}
